def _segment(src: str, decl: str) -> str:
    """Полный сегмент: объявление + тело до следующего 'pattern '."""
    start = src.index(decl)
    rest = src[start + len(decl):]
    nxt = rest.find("\npattern ")
    body = rest[:nxt] if nxt != -1 else rest
    return decl + body


